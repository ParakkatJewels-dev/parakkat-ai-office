// Writes supabase/seed.sql from the office roster, so the database org chart matches the 3D campus.
// Run: node scripts/gen-seed.mjs
import { writeFileSync } from 'node:fs';
import { BUILDINGS, ROOMS, PEOPLE, HUMAN_HEAD, teamLead } from '../src/office/roster.mjs';

const q = v => v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const ROLE = { superAdmin: 'super_admin', creativeHead: 'creative_head', ecomManager: 'ecom_manager', perfMarketer: 'perf_marketer' };
const bname = Object.fromEntries(BUILDINGS.map(b => [b.id, b.name]));

const depts = ROOMS.map(r => `  (${q(r.id)}, ${q(r.name)}, ${q(bname[r.building])}, ${q(ROLE[HUMAN_HEAD[r.id]])}, ${q(teamLead(r.id) || null)})`);
const agents = PEOPLE.filter(p => !p.human).map(p => `  (${q(p.id)}, ${q(p.name)}, ${q(p.role)}, ${q(p.room)}, ${!!p.head}, ${q(p.model)})`);

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), `-- Generated by scripts/gen-seed.mjs from src/office/roster.mjs. Do not edit by hand.
insert into departments (id, name, building, human_head_role, ai_lead_agent) values
${depts.join(',\n')}
on conflict (id) do update set name = excluded.name, building = excluded.building, ai_lead_agent = excluded.ai_lead_agent;

insert into agents (id, name, role_desc, department_id, is_lead, model) values
${agents.join(',\n')}
on conflict (id) do update set name = excluded.name, role_desc = excluded.role_desc, department_id = excluded.department_id, is_lead = excluded.is_lead, model = excluded.model;

insert into connections (provider) values ('shopify'), ('meta'), ('instagram'), ('google_ads'), ('ga4'), ('triple_whale'), ('openai'), ('gemini'), ('jev'), ('google_trends'), ('keyword_planner')
on conflict do nothing;
`);
console.log(`seed.sql: ${depts.length} departments, ${agents.length} agents`);
